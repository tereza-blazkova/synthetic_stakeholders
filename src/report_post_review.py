"""
LaTeX macros for the post-review numbers (long paper and poster), from analysis/results/post_review/.

    python -m src.post_review_analysis && python -m src.score_post_review   # make the CSVs
    python -m src.report_post_review                                        # -> analysis/tables/numbers_post_review.tex

Every macro always exists, so the documents compile at any stage:
  - a value that is not available yet is written as \\PH{<name>} (red box);
  - a B1-B4 value from fewer runs than planned is wrapped in \\Interim{...} (orange), with
    the run count in the macro \\<name>N.
With \\def\\phfinal{} before \\input, any \\PH or \\Interim stops the build, so nothing
unfinished can go out. Numbers are never typed into the prose.
Macro names: letters only (A1..B4 spelled out), family last: \\bOneReservationsReversedGemma.
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "analysis" / "results" / "post_review"
OUT = ROOT / "analysis" / "tables" / "numbers_post_review.tex"
FAMILIES = ["Qwen", "Gemma", "Mistral"]
PLANNED_RUNS = 20

# B1 conditions (inputs/variants/card_variants.yaml) -> macro part
B1_CONDS = {"baseline_replay": "Control", "reversed_order": "Reversed", "reservations_fourth": "ResFourth",
            "shuffled_per_agent": "Shuffled", "symmetric_definitions": "Symmetric",
            "definitions_removed": "NoDefs", "conditional_label": "Conditional",
            "no_reservations_word": "NoResWord", "no_legitimacy_bullet": "NoLegitimacy",
            "no_majority_claim": "NoMajority"}
B1_OPTIONS = {"support": "Support", "support_with_reservations": "Reservations",
              "object_no_block": "Object", "block": "Block"}
# B2-B4 conditions (folder names under runs/post_review/) -> macro part; model key -> family
B234_CONDS = {"personas_a": "bTwoA", "personas_b": "bTwoB", "precision_q8": "bFour", "larger_qwen122": "bThree",
              "precision_fp16": "bFourFull"}   # bFourFull: post-hoc Gemma 16-bit (2026-11-09)
B234_FAMILIES = {"bThree": ["Qwen"], "bFourFull": ["Gemma"]}   # B3 Qwen only; fp16 Gemma only
FAMILY_OF = {"qwen3.5": "Qwen", "gemma3": "Gemma", "mistral-small3.2": "Mistral"}

HEADER = r"""% Generated by src/report_post_review.py from analysis/results/post_review/. Do not edit by hand.
% Load in the preamble. Put \def\phfinal{} before \input to make any placeholder an error.
\makeatletter
\@ifundefined{PH}{%
  \RequirePackage{xcolor}%
  \ifdefined\phfinal
    \newcommand{\PH}[1]{\PackageError{numbers}{Placeholder #1 not filled}{Run the scoring and src.report_post_review}}%
    \newcommand{\Interim}[1]{\PackageError{numbers}{Interim value #1}{Wait for all runs}}%
  \else
    \newcommand{\PH}[1]{\textcolor{red}{\fbox{\scriptsize\ttfamily #1}}\PackageWarning{numbers}{Placeholder #1}}%
    \newcommand{\Interim}[1]{\textcolor{orange!85!black}{#1}}%
  \fi}{}
\makeatother
"""


def _rows(name: str) -> list[dict]:
    p = RES / name
    return list(csv.DictReader(p.open())) if p.exists() else []


def _pct(x) -> str:
    return f"{round(100 * float(x))}\\%"


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.names: set[str] = set()

    def put(self, name: str, value: str | None, interim: bool = False) -> None:
        assert name.isalpha(), name
        assert name not in self.names, name
        self.names.add(name)
        if value is None or value == "":
            body = f"\\PH{{{name}}}"
        else:
            body = f"\\Interim{{{value}}}" if interim else value
        self.lines.append(f"\\newcommand{{\\{name}}}{{{body}}}")


def a_section(m: Macros) -> None:
    a1 = (_rows("a1_random_floor.csv") or [{}])[0]
    m.put("aOneRulesMean", a1.get("rules_mean"))
    m.put("aOneRulesLo", a1.get("rules_p2.5"))
    m.put("aOneRulesHi", a1.get("rules_p97.5"))
    m.put("aOneDecision", _pct(a1["decision_match_rate"]) if a1 else None)
    a3 = {r["family"]: r for r in _rows("a3_within_family_spread.csv")}
    a4 = {r["family"]: r for r in _rows("a4_start_vs_change.csv")}
    for f in FAMILIES:
        r = a3.get(f, {})
        m.put(f"aThreeMean{f}", r.get("rules_mean"))
        m.put(f"aThreeCI{f}", f"[{r['ci_lo']}, {r['ci_hi']}]" if r else None)
        m.put(f"aThreeSD{f}", r.get("sd"))
        m.put(f"aThreeConfigs{f}", r.get("distinct_rule_configs"))
        m.put(f"aThreeModels{f}", r.get("distinct_selected_models"))
        r = a4.get(f, {})
        m.put(f"aFourBaseline{f}", r.get("rules_baseline_mean"))
        m.put(f"aFourEndline{f}", r.get("rules_endline_mean"))
        m.put(f"aFourAlready{f}", _pct(r["share_endline_mismatch_already_at_baseline"]) if r else None)
        m.put(f"aFourRepeated{f}", _pct(r["human_moves_repeated_share"]) if r else None)
    a5 = _rows("a5_vote_vs_own_answers.csv")
    for f in FAMILIES:
        low = [r for r in a5 if r["family"] == f and int(r["own_rules_matched_by_panel"]) <= 3]
        n = sum(int(r["n_agents"]) for r in low)
        k = sum(int(r["n_agents"]) for r in low if r["vote"] == "support_with_reservations")
        m.put(f"aFiveLow{f}", str(n) if a5 else None)
        m.put(f"aFiveLowRes{f}", str(k) if a5 else None)
    a6 = {(r["family"], r["theme"]): r for r in _rows("a6_content_themes.csv")}
    for f in FAMILIES:
        for theme, part in [("purpose", "Purpose"), ("surveillance_privacy", "Surveillance"),
                            ("disagreement", "Disagreement"), ("stigma_harm", "Stigma")]:
            r = a6.get((f, theme))
            m.put(f"aSix{part}{f}", _pct(r["share_runs"]) if r else None)


def b1_section(m: Macros) -> None:
    rows = {(r["family"], r["condition"]): r for r in _rows("b1_card_conditions.csv")}
    for f in FAMILIES + ["Pooled"]:
        key = "pooled" if f == "Pooled" else f
        ns = [int(r["n_runs"]) for (fam, _), r in rows.items() if fam == key]
        n = min(ns) if ns else None
        if f == "Pooled":   # pooled rows count runs over all three families
            n = int(rows[(key, "baseline_replay")]["n_runs"]) if (key, "baseline_replay") in rows else None
        interim = n is not None and n < PLANNED_RUNS * (len(FAMILIES) if f == "Pooled" else 1)
        m.put(f"bOneN{f}", str(n) if n is not None else None)
        for cond, cpart in B1_CONDS.items():
            r = rows.get((key, cond))
            for opt, opart in B1_OPTIONS.items():
                m.put(f"bOne{opart}{cpart}{f}", _pct(r[f"{opt}_share"]) if r else None, interim)
            m.put(f"bOneCI{cpart}{f}", r["support_with_reservations_ci"] if r else None, interim)
            if cond != "baseline_replay":
                m.put(f"bOneChanged{cpart}{f}", _pct(r["paired_changed_share"]) if r and r["paired_changed_share"] else None, interim)
        r = rows.get((key, "baseline_replay"))
        m.put(f"bOneSameOrig{f}", _pct(r["same_as_original_vote_share"]) if r else None, interim)


def b234_section(m: Macros) -> None:
    rows = {}
    for r in _rows("b234_runs.csv"):
        fam = next(v for k, v in FAMILY_OF.items() if r["model"].startswith(k))
        rows[(r["condition"], fam)] = r
    for cond, cpart in B234_CONDS.items():
        for f in B234_FAMILIES.get(cpart, FAMILIES):
            r = rows.get((cond, f))
            interim = bool(r) and int(r["n_runs"]) < PLANNED_RUNS
            m.put(f"{cpart}N{f}", r["n_runs"] if r else None)
            m.put(f"{cpart}Rules{f}", r["rules_mean"] if r else None, interim)
            m.put(f"{cpart}RulesRef{f}", r["ref_rules_mean_all20"] if r else None)
            m.put(f"{cpart}Diff{f}", r["diff_rules_vs_ref"] if r else None, interim)
            m.put(f"{cpart}DiffCI{f}", r["diff_ci"] if r else None, interim)
            m.put(f"{cpart}Decision{f}", r["human_model"] if r else None, interim)
            m.put(f"{cpart}Modal{f}", r["modal_share"] if r else None, interim)
            m.put(f"{cpart}Reservations{f}", _pct(r["reservations_share"]) if r else None, interim)
            m.put(f"{cpart}ReservationsRef{f}", _pct(r["ref_reservations_share"]) if r else None)


def main() -> None:
    m = Macros()
    a_section(m)
    b1_section(m)
    b234_section(m)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "\n".join(m.lines) + "\n")
    n_ph = sum("\\PH{" in line for line in m.lines)
    n_int = sum("\\Interim{" in line for line in m.lines)
    print(f"{OUT.relative_to(ROOT)}: {len(m.lines)} macros, {n_ph} placeholders, {n_int} interim")


if __name__ == "__main__":
    main()
